"""Portable framing/lifecycle tests for bounded original-child Save witnesses."""

import io
import json
from pathlib import Path
import subprocess
import sys
import threading
import time
import tracemalloc
import unittest
from unittest.mock import patch

import save_diagnostic as diagnostic

ROOT = Path(__file__).resolve().parents[2]


def wire(*stages):
    """Construct only fixed protocol frames for deterministic fixtures."""
    return b"".join(diagnostic.PREFIX + stage.encode("ascii") + b"\n" for stage in stages)


class GeneratedStream:
    """Produce multi-megabyte unterminated output without a large test allocation."""

    def __init__(self, length, suffix=b""):
        """Declare remaining generated bytes and a small recovery suffix."""
        self.remaining, self.suffix = length, suffix
        self.largest_read = 0
        self.closed = False

    def read(self, size):
        """Honor the requested fixed-size read throughout generated/suffix output."""
        self.largest_read = max(self.largest_read, size)
        if self.remaining:
            count = min(size, self.remaining)
            self.remaining -= count
            return b"q" * count
        result, self.suffix = self.suffix[:size], self.suffix[size:]
        return result

    def close(self):
        """Record the collector's reader-owned stream teardown."""
        self.closed = True


class SaveDiagnosticTests(unittest.TestCase):
    """Verify privacy, bounded buffering, censored negatives and kill retention."""

    def collect(self, data):
        """Drain finite test bytes to EOF and return the detached snapshot."""
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(io.BytesIO(data))
        return collector.finish(original_normal_exit=True)

    def test_normal_watermark_and_duplicates(self):
        """Preserve duplicate positive markers and do not fabricate execution times."""
        result = self.collect(wire("ready", "selector_entered", "selector_entered",
                                   "controller_admitted", "completed"))
        self.assertTrue(result["healthy_completed_stream"])
        self.assertEqual(result["stage_counts"]["selector_entered"], 2)
        self.assertEqual([row["stage"] for row in result["records"]],
                         ["ready", "selector_entered", "selector_entered", "controller_admitted", "completed"])
        self.assertTrue(all(row["parent_receipt_ms"] >= 0 for row in result["records"]))
        self.assertEqual(result["absence_interpretation"], "not-proof-of-callback-nonexecution")

    def test_terminal_eof_requires_independent_normal_exit(self):
        """A received terminal plus EOF cannot certify an unknown/forced child exit."""
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(io.BytesIO(wire("ready", "selector_entered", "controller_admitted", "completed")))
        unknown = collector.finish()
        forced = collector.finish(original_normal_exit=False)
        self.assertTrue(forced["eof"])
        self.assertEqual(forced["stage_counts"]["completed"], 1)
        self.assertEqual(forced["stage_counts"]["controller_admitted"], 1)
        for result in (unknown, forced):
            self.assertFalse(result["original_normal_exit"])
            self.assertFalse(result["healthy_completed_stream"])
            self.assertEqual(result["stream_completion"], "censored")
        normal = collector.finish(original_normal_exit=True)
        self.assertTrue(normal["healthy_completed_stream"])
        self.assertEqual(normal["stream_completion"], "healthy-full-session-transport")
        self.assertFalse(forced["healthy_completed_stream"])

    def test_huge_unterminated_stream_memory_and_tail(self):
        """An 8 MiB no-LF frame never allocates a matching buffer or retained text."""
        stream = GeneratedStream(8 * 1048576)
        collector = diagnostic.SaveDiagnosticCollector()
        tracemalloc.start()
        try:
            collector.attach(stream)
            result = collector.finish()
            _, peak = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        self.assertFalse(result["join_timeout"])
        self.assertTrue(result["partial_tail"])
        self.assertEqual(result["overlong_frames"], 1)
        self.assertEqual(result["records"], [])
        self.assertLess(peak, 131072)
        self.assertEqual(stream.largest_read, diagnostic.READ_BYTES)
        self.assertTrue(stream.closed)

    def test_overlong_recovers_at_newline(self):
        """An overlong line cannot embed a fake stage; framing resumes after LF."""
        stream = GeneratedStream(3 * 1048576, wire("selector_entered") + b"\n" + wire("ready", "completed"))
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(stream)
        result = collector.finish()
        self.assertEqual(result["stage_counts"]["selector_entered"], 0)
        self.assertEqual(result["stage_counts"]["completed"], 1)
        self.assertTrue(result["malformed"])
        self.assertFalse(result["healthy_completed_stream"])

    def test_unknown_nonascii_partial_tail_not_retained(self):
        """Rejected stderr content and a partial valid-looking tail never escape."""
        secret = b"foreign private path content"
        result = self.collect(wire("ready") + secret + b"\n" + b"\xff\xfe\n" + wire("completed") + diagnostic.PREFIX)
        self.assertEqual(result["rejected_frames"], 2)
        self.assertTrue(result["partial_tail"])
        self.assertNotIn(secret.decode(), json.dumps(result))
        self.assertFalse(result["healthy_completed_stream"])

    def test_record_cap_still_drains_terminal(self):
        """Retention saturation cannot strand the producer or conceal later EOF."""
        result = self.collect(wire("ready", *("selector_entered",) * 100, "controller_admitted", "completed"))
        self.assertEqual(len(result["records"]), 16)
        self.assertEqual(result["stage_counts"]["selector_entered"], 100)
        self.assertEqual(result["stage_counts"]["completed"], 1)
        self.assertTrue(result["retention_loss"])
        self.assertTrue(result["eof"])
        self.assertFalse(result["healthy_completed_stream"])
        self.assertLess(len(json.dumps(result).encode("ascii")), 4096)

    def test_saturated_counter_keeps_draining(self):
        """Counter saturation is explicit and completion remains observable."""
        with patch.object(diagnostic, "COUNT_LIMIT", 3):
            result = self.collect(wire("ready", *("selector_entered",) * 5, "completed"))
        self.assertEqual(result["stage_counts"]["selector_entered"], 3)
        self.assertTrue(result["counter_capped"])
        self.assertTrue(result["eof"])
        self.assertEqual(result["stage_counts"]["completed"], 1)

    def test_overflow_censors_completed(self):
        """A target loss marker makes even EOF plus completed an unhealthy stream."""
        result = self.collect(wire("ready", "overflow", "completed"))
        self.assertTrue(result["loss"])
        self.assertFalse(result["healthy_completed_stream"])

    def test_invalid_order_censors_completed(self):
        """Terminal-first, admission-before-selector and duplicate ready cannot certify health."""
        for stages in (("completed", "ready"), ("ready", "controller_admitted", "completed"),
                       ("ready", "ready", "completed"), ("ready", "completed", "selector_entered")):
            with self.subTest(stages=stages):
                result = self.collect(wire(*stages))
                self.assertFalse(result["protocol_order_valid"])
                self.assertFalse(result["healthy_completed_stream"])

    def test_fragmented_frames(self):
        """Single-byte reads preserve framing without relying on pipe chunk boundaries."""
        class Fragmented(io.BytesIO):
            """Force arbitrary frame splits using one-byte reads."""
            def read(self, size):
                """Return no more than one byte from the finite fixture."""
                return super().read(1)
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(Fragmented(wire("ready", "selector_entered", "controller_admitted", "completed")))
        self.assertTrue(collector.finish(original_normal_exit=True)["healthy_completed_stream"])

    def test_read_error_is_content_free(self):
        """Transport exception text is discarded, not surfaced in the JSON report."""
        class Broken:
            """Model a pipe failure containing sensitive exception text."""
            def read(self, size):
                """Raise without returning a frame."""
                raise OSError("secret foreign document")
            def close(self):
                """Permit reader-owned closure after failure."""
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(Broken())
        result = collector.finish()
        self.assertTrue(result["read_error"])
        self.assertFalse(result["eof"])
        self.assertNotIn("secret", json.dumps(result))

    def test_reader_start_failure_is_censored(self):
        """Thread-start failure cannot escape attach or fabricate healthy completion."""
        collector = diagnostic.SaveDiagnosticCollector()
        stream = io.BytesIO(wire("ready", "completed"))
        try:
            with patch.object(diagnostic.threading.Thread, "start", side_effect=RuntimeError("private thread text")):
                collector.attach(stream)
            result = collector.finish()
            self.assertTrue(result["attach_error"])
            self.assertFalse(result["eof"])
            self.assertFalse(result["healthy_completed_stream"])
            self.assertNotIn("private thread text", json.dumps(result))
        finally:
            stream.close()

    def test_blocked_read_join_is_bounded_and_snapshot_stable(self):
        """Join timeout must not close a blocked pipe or mutate the retained snapshot."""
        release = threading.Event()
        class Blocked:
            """Hold a read until the test explicitly releases the owned stream."""
            closed = False
            def read(self, size):
                """Simulate a writer/pipe that outlives bounded teardown."""
                release.wait()
                return b""
            def close(self):
                """Observe teardown only after the reader is no longer blocked."""
                self.closed = True
        stream = Blocked()
        collector = diagnostic.SaveDiagnosticCollector()
        collector.attach(stream)
        started = time.monotonic()
        try:
            with patch.object(diagnostic, "JOIN_SECONDS", 0.02):
                result = collector.finish()
            self.assertLess(time.monotonic() - started, 1)
            self.assertTrue(result["join_timeout"])
            self.assertFalse(stream.closed)
        finally:
            release.set()
            collector._thread.join(2)
        self.assertTrue(collector.finish()["eof"])
        self.assertFalse(result["eof"])

    def test_actual_child_kill_retains_already_received_markers(self):
        """Real inherited stderr preserves positive facts received before forced kill."""
        collector = diagnostic.SaveDiagnosticCollector()
        child = subprocess.Popen([sys.executable, "-B", "-c",
                                  "import os,time;os.write(2,b'mote-save-diag-v1:ready\\n'"
                                  "b'mote-save-diag-v1:selector_entered\\n'"
                                  "b'mote-save-diag-v1:completed\\n');time.sleep(30)"],
                                 cwd=ROOT, stderr=subprocess.PIPE, stdout=subprocess.DEVNULL, bufsize=0)
        collector.attach(child.stderr)
        try:
            deadline = time.monotonic() + 5
            while time.monotonic() < deadline:
                with collector._lock:
                    received = collector._counts["completed"] == 1
                if received:
                    break
                time.sleep(0.01)
            self.assertTrue(received)
        finally:
            child.kill()
            child.wait(timeout=5)
        result = collector.finish()
        self.assertTrue(result["eof"])
        self.assertEqual(result["stage_counts"]["selector_entered"], 1)
        self.assertEqual(result["stage_counts"]["completed"], 1)
        self.assertFalse(result["original_normal_exit"])
        self.assertFalse(result["healthy_completed_stream"])
        self.assertEqual(result["stream_completion"], "censored")


if __name__ == "__main__":
    unittest.main()
